const {randomUUID}=require('node:crypto');
module.exports=async({client,one,check,request,authBase,organization,adminA,kcca,system,driverA,a})=>{
 const path='/api/auth/organization-onboarding';
 const issue=(actor,org,email)=>request(actor,path+'/'+org+'/invitations','POST',{email},authBase);
 const accept=(token,email)=>request(null,path+'/accept','POST',{token,email,fullName:'Setup fixture admin',password:'Rollback-only-password-123'},authBase);
 const org=await organization('Rollback onboarding'),email=randomUUID()+'@rollback.invalid';
 check((await issue(adminA,org,email)).status===403,'Company cannot issue administrator invitation');
 check((await issue(driverA,org,email)).status===403,'Driver cannot issue invitation');
 check((await issue(kcca,a,email)).status===409,'Existing administrator cannot be replaced');
 const issued=await issue(kcca,org,email);
 check(issued.status===201,'KCCA issues first-admin invitation');
 const {id,token}=issued.body.data;
 const stored=await one('SELECT token_hash FROM organization_admin_invitations WHERE id=$1',[id]);
 check(stored.token_hash!==token&&stored.token_hash.length===64,'Only a token digest is stored');
 const view=await request(kcca,path+'/'+org,'GET',undefined,authBase);
 check(view.status===200&&!JSON.stringify(view.body).includes(token)&&!JSON.stringify(view.body).includes(stored.token_hash),'Status response never reveals token or digest');
 check((await accept(token,'wrong@rollback.invalid')).status===400,'Invited email binding enforced');
 check(!(await one('SELECT id FROM users WHERE lower(email)=lower($1)',[email])),'Failed acceptance creates no account');
 check((await accept(token,email)).status===201,'Recipient creates first administrator');
 const user=await one('SELECT id FROM users WHERE lower(email)=lower($1)',[email]);
 check(!!await one("SELECT 1 FROM organization_effective_permissions($1,$2) WHERE code='access.manage'",[user.id,org]),'Accepted admin has scoped membership and permissions');
 const login=await request(null,'/api/auth/login','POST',{email,password:'Rollback-only-password-123'},authBase);
 check(login.status===200,'New administrator can log in');
 check((await accept(token,email)).status===400,'Setup link cannot be reused');
 check((await issue(system,org,randomUUID()+'@rollback.invalid')).status===409,'Even system actor cannot replace accepted first admin through setup');
 const org2=await organization('Rollback setup expiry');
 const email2=randomUUID()+'@rollback.invalid';
 const expired=await issue(system,org2,email2);
 check(expired.status===201,'System administrator can issue invitation');
 await client.query("UPDATE organization_admin_invitations SET expires_at=CURRENT_TIMESTAMP-INTERVAL '1 second' WHERE id=$1",[expired.body.data.id]);
 check((await accept(expired.body.data.token,email2)).status===400,'Expired link rejected');
 const replacement=await issue(system,org2,email2);
 check(replacement.status===201,'Expired pending invitation can be replaced');
 check(!!(await one('SELECT revoked_at FROM organization_admin_invitations WHERE id=$1',[expired.body.data.id])).revoked_at,'Replacement revokes old invitation');
 const revoked=await request(system,path+'/'+org2+'/invitations/'+replacement.body.data.id,'DELETE',undefined,authBase);
 check(revoked.status===200,'Pending link can be revoked');
 check((await accept(replacement.body.data.token,email2)).status===400,'Revoked link rejected');
 check((await accept(replacement.body.data.token,email2)).status===429,'Public setup attempts rate limited');
 await client.query('UPDATE organizations SET is_active=false WHERE id=$1',[org2]);
 check((await issue(kcca,org2,email2)).status===404,'Inactive company cannot onboard');
 await client.query('UPDATE organizations SET is_active=true WHERE id=$1',[org2]);
 check((await issue(kcca,org2,email)).status===409,'Existing email cannot be transferred');
 const event=await one("SELECT actor_id,new_value FROM organization_audit_events WHERE entity_id=$1 AND action='invitation_accepted'",[id]);
 check(event.actor_id===user.id&&!JSON.stringify(event.new_value).includes(token),'Acceptance audit records actor without secret');
 process.env.WMS_ONBOARDING_ENABLED='false';
 check((await issue(kcca,org2,email2)).status===503,'Deployment flag fails closed');
 process.env.WMS_ONBOARDING_ENABLED='true';
 console.log('PASS: first-admin invitation lifecycle and access boundaries.');
};
