import {NextFunction,Request,Response,Router} from 'express';
import {requireRoles} from '../middlewares/auth.middleware';
import {getRecycling,patchMaterialState,patchPartnerState,patchPurchaseDueDate,patchSaleDueDate,payPurchase,paySale,postLot,postManagerFloat,postMaterial,postPartner,postPaymentFollowUp,postSale,postSorting,postStockAdjustment} from '../controllers/recycling.controller';
const r=Router(),run=(h:(q:Request,s:Response)=>Promise<unknown>)=>async(q:Request,s:Response,n:NextFunction)=>{try{await h(q,s)}catch(e){n(e)}};
const manage=requireRoles('company_admin','supervisor'),view=requireRoles('company_admin','supervisor','recycling_collector','recycling_sales'),collect=requireRoles('company_admin','supervisor','recycling_collector'),sell=requireRoles('company_admin','supervisor','recycling_collector','recycling_sales'),industrial=requireRoles('company_admin','supervisor','recycling_sales');
r.get('/recycling',view,run(getRecycling));
r.post('/recycling/lots',collect,run(postLot));
r.post('/recycling/sales',sell,run(postSale));
r.post('/recycling/manager-float',manage,run(postManagerFloat));
r.post('/recycling/sorting',manage,run(postSorting));
r.post('/recycling/stock-adjustments',manage,run(postStockAdjustment));
r.post('/recycling/partners',industrial,run(postPartner));
r.patch('/recycling/partners/:id/status',industrial,run(patchPartnerState));
r.post('/recycling/materials',manage,run(postMaterial));
r.patch('/recycling/materials/:id/status',manage,run(patchMaterialState));
r.patch('/recycling/lots/:id/paid',manage,run(payPurchase));
r.patch('/recycling/sales/:id/paid',industrial,run(paySale));
r.patch('/recycling/lots/:id/due-date',manage,run(patchPurchaseDueDate));
r.patch('/recycling/sales/:id/due-date',industrial,run(patchSaleDueDate));
r.post('/recycling/sales/:id/follow-ups',industrial,run(postPaymentFollowUp));
export default r;
